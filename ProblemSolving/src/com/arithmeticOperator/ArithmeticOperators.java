package com.arithmeticOperator;

public class ArithmeticOperators {
	public static void main(String[] args) {
	
		//ADDITION
		int i = 10;
	int j = 40;
	
	int result = i+j;
	
	System.out.println("Addition of two Numbers : "+result);
	
	//SUBSTRACTION
	int k= 90;
	int l= 70;
	int result1 = k-l;
	System.out.println("Substraction of two Numbers : "+result1);
		
	//MULTIPLICATION
	int m = 55;
	int n= 33;
	int result2 = m*n;
	System.out.println("Multiplication of two Numbers : "+ result2);
		
	//DIVISION
	int o = 80;
	int p = 5;
	int result3 = o/p;
	System.out.println("Division of two Numbers : "+ result3);
	
	//MODULUS
	int q= 60;
	int r = 20;
	int result4 = q%r;
	System.out.println("Remainder : "+ result4);
	System.out.println();
	double x= 50;
	double y = 4;
	
	System.out.println("ADDITION = "+ (x+y));
	System.out.println("SUBSTRACTION = "+ (x-y));
	System.out.println("MULTIPLICATION = "+ (x*y));
	System.out.println("DIVISION = "+ (x/y));
	System.out.println("MODULUS = "+ (x%y));
	}
	
	
	

}
